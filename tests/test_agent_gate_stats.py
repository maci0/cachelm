"""Host-gate instrumentation for agent battery / paper dual metrics."""

from __future__ import annotations

from ll3m.agent import AgentConfig, host_assist_call, run_agent


def test_host_assist_intent():
    assert host_assist_call("hello") is None
    assert host_assist_call("what is 5+5") is not None
    assert "time" in (host_assist_call("what day is it") or "")


def test_gate_blocks_false_call():
    def gen_false(prompt: str, **kw) -> str:
        return "<call>lookup pizza</call> nowhere"

    cfg = AgentConfig(gate_tools=True, assist_tools=False, temperature=0.0, top_k=1)
    turn = run_agent("hello", gen_false, cfg=cfg)
    assert turn.gold_needs_tool is False
    assert turn.model_emitted_call is True
    assert any(e.get("kind") == "block_false_call" for e in turn.gate_events)
    assert turn.tool_trace == []


def test_pure_does_not_block_false_call():
    def gen_false(prompt: str, **kw) -> str:
        return "<call>lookup pizza</call> nowhere"

    cfg = AgentConfig(gate_tools=False, assist_tools=False, temperature=0.0, top_k=1)
    turn = run_agent("hello", gen_false, cfg=cfg)
    assert turn.model_emitted_call is True
    assert not any(e.get("kind") == "block_false_call" for e in turn.gate_events)
    assert turn.tool_trace  # executed (may ERROR)


def test_gate_rewrites_wrong_tool():
    def gen_wrong(prompt: str, **kw) -> str:
        return "<call>lookup day</call>"

    cfg = AgentConfig(gate_tools=True, assist_tools=False, temperature=0.0, top_k=1)
    turn = run_agent("what day is it", gen_wrong, cfg=cfg)
    assert any(e.get("kind") == "rewrite_tool" for e in turn.gate_events)
    assert turn.tool_trace and turn.tool_trace[0].get("tool") == "time"


def test_set_kb_empty_and_restore():
    from ll3m.agent import host_assist_call
    from ll3m.tools import get_kb, kb_size, set_kb, tool_lookup

    n0 = kb_size()
    assert n0 > 100
    try:
        set_kb({})
        assert kb_size() == 0
        assert len(get_kb()) == 0
        err = tool_lookup("capital france")
        assert err.startswith("ERROR")
        # B1: empty KB → no invented *lookup* (regex capital/pi nor table scan).
        # Wiki fallback on "what is …" may still fire; that is not closed-KB.
        for q in (
            "what is the capital of france",
            "capital of france",
            "capital france",
            "what is pi",
            "water formula",
        ):
            assist = host_assist_call(q)
            assert assist is None or "lookup" not in assist, (q, assist)
        # bare key only hit the table path
        assert host_assist_call("capital france") is None
    finally:
        set_kb(None)
    assert kb_size() == n0
    assert "Paris" in tool_lookup("capital france")
    # restored assist path works again
    restored = host_assist_call("capital of france")
    assert restored is not None and "lookup" in restored


def test_battery_dual_score_fields():
    """Schema: dual pure metrics always present on report-shaped dicts."""
    from scripts.eval_agent_battery import CaseResult

    # Emission-aware fails no_call when a tool executed; user-visible may pass
    # if final text is clean (fixture only — no model).
    r_fail = CaseResult(
        name="no_call:fixture",
        category="no_call",
        user="hello",
        ok=False,
        detail="unexpected_tool:['lookup']",
        final="Hello! How can I help?",
        executed_tools=["lookup"],
        model_emitted_call=True,
        gold_needs_tool=False,
        ok_user_visible=True,
        detail_user_visible="pass",
    )
    r_ok = CaseResult(
        name="calc:fixture",
        category="calc",
        user="2+2",
        ok=True,
        detail="pass",
        final="4",
        executed_tools=["calc"],
        model_emitted_call=True,
        gold_needs_tool=True,
        ok_user_visible=True,
        detail_user_visible="pass",
    )
    results = [r_fail, r_ok]
    n_ok = sum(1 for r in results if r.ok)
    n_uv = sum(1 for r in results if r.ok_user_visible)
    assert n_ok == 1
    assert n_uv == 2
    report = {
        "total": len(results),
        "passed": n_ok,
        "pass_rate": n_ok / len(results),
        "passed_user_visible": n_uv,
        "pass_rate_user_visible": n_uv / len(results),
        "scoring_note": (
            "Freeze pure 90/101 is a historical stream-visible pin, "
            "not regenerated by either scorer."
        ),
    }
    assert "passed_user_visible" in report
    assert "scoring_note" in report
    assert report["passed"] == 1
    assert report["passed_user_visible"] == 2
